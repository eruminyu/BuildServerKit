function httpsGetText(url, timeoutMs = 8000) {
  return new Promise((resolve, reject) => {
    const req = https.get(url, { timeout: timeoutMs }, (res) => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
        return resolve(httpsGetText(res.headers.location, timeoutMs));
      }
      if (res.statusCode !== 200) {
        res.resume();
        return reject(new Error(`HTTP ${res.statusCode}`));
      }
      const chunks = [];
      res.on('data', (c) => chunks.push(c));
      res.on('end', () => resolve(Buffer.concat(chunks).toString('utf8')));
    });
    req.on('error', reject);
    req.on('timeout', () => req.destroy(new Error('요청 시간 초과')));
  });
}

function httpsDownloadFile(url, destPath, onProgress = () => {}) {
  return new Promise((resolve, reject) => {
    const req = https.get(url, { timeout: 60000 }, (res) => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
        return resolve(httpsDownloadFile(res.headers.location, destPath, onProgress));
      }
      if (res.statusCode !== 200) {
        res.resume();
        return reject(new Error(`다운로드 실패 (HTTP ${res.statusCode})`));
      }
      const total = Number(res.headers['content-length']) || 0;
      let received = 0;
      const out = fs.createWriteStream(destPath);
      res.on('data', (chunk) => {
        received += chunk.length;
        if (total > 0) onProgress(Math.round((received / total) * 100));
      });
      res.pipe(out);
      out.on('finish', () => out.close(() => resolve(destPath)));
      out.on('error', (err) => reject(err));
    });
    req.on('error', reject);
    req.on('timeout', () => req.destroy(new Error('다운로드 시간 초과')));
  });
}

function runElevatedPowerShell(scriptBody) {
  return new Promise((resolve) => {
    const tmpDir = os.tmpdir();
    const stamp = `${Date.now()}_${Math.floor(Math.random() * 10000)}`;
    const psFile = path.join(tmpDir, `bsk_admin_${stamp}.ps1`);
    const logFile = path.join(tmpDir, `bsk_admin_${stamp}.log`);

    const wrapped = [
      '$ErrorActionPreference = "Continue"',
      '[Console]::OutputEncoding = [System.Text.Encoding]::UTF8',
      `Start-Transcript -Path '${logFile.replace(/'/g, "''")}' -Force | Out-Null`,
      'try {',
      scriptBody,
      '  $scriptExit = 0',
      '} catch {',
      '  Write-Output ("[ERROR] " + $_.Exception.Message)',
      '  $scriptExit = 1',
      '} finally {',
      '  Stop-Transcript | Out-Null',
      '}',
      'exit $scriptExit',
    ].join('\r\n');

    const bom = Buffer.from([0xef, 0xbb, 0xbf]);
    fs.writeFileSync(psFile, Buffer.concat([bom, Buffer.from(wrapped, 'utf8')]));

    const launcher = `try { $p = Start-Process powershell.exe -Verb RunAs -Wait -PassThru -ArgumentList @('-NoProfile','-ExecutionPolicy','Bypass','-File','${psFile.replace(/'/g, "''")}'); exit $p.ExitCode } catch { Write-Error $_.Exception.Message; exit 1223 }`;

    execCapture('powershell.exe', ['-NoProfile', '-ExecutionPolicy', 'Bypass', '-Command', launcher], { timeoutMs: 120000 }).then((res) => {
      let log = '';
      try {
        if (fs.existsSync(logFile)) log = fs.readFileSync(logFile, 'utf8');
      } catch {}
      try { fs.unlinkSync(psFile); } catch {}
      try { fs.unlinkSync(logFile); } catch {}
      resolve({
        ok: res.code === 0,
        code: res.code,
        canceled: res.code === 1223,
        output: (log || res.stdout || res.stderr || '').trim(),
      });
    });
  });
}

