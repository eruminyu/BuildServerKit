const RESERVED_NAMES = new Set([
  'engine',
  'unreal',
  'game',
  'editor',
  'core',
  'default',
  'tp_blank',
  'tp_blankbp',
  'con',
  'prn',
  'aux',
  'nul',
  'com1',
  'lpt1',
]);

const TEXT_EXTENSIONS = new Set(['.uproject', '.cs', '.cpp', '.h', '.hpp', '.c', '.ini', '.json', '.txt', '.md']);
const SKIP_DIR_NAMES = new Set(['media', 'saved', 'intermediate', 'binaries', 'deriveddatacache', '.vs', '.git']);
const SKIP_FILE_NAMES = new Set(['templatedefs.ini', 'thumbs.db', 'desktop.ini']);

function validateProjectName(rawName) {
  const name = String(rawName || '').trim();
  if (!name) {
    throw new Error('프로젝트 이름을 입력해 주세요. (예: Project_MurMur)');
  }
  if (name.length < 2 || name.length > 20) {
    throw new Error('UE5 프로젝트 이름은 2~20자 사이여야 합니다. (Windows 경로 길이 제한 보호)');
  }
  if (!/^[A-Za-z][A-Za-z0-9_]*$/.test(name)) {
    throw new Error('프로젝트 이름은 영문으로 시작해야 하며 영문·숫자·밑줄(_)만 사용할 수 있습니다. (한글/공백/하이픈 불가)');
  }
  if (RESERVED_NAMES.has(name.toLowerCase())) {
    throw new Error(`'${name}'은(는) Unreal Engine 예약어이므로 다른 이름을 사용해 주세요.`);
  }
  return name;
}

function readEngineVersionInfo(ueRoot, fallbackVersion = '') {
  const verFile = path.join(ueRoot, 'Engine', 'Build', 'Build.version');
  if (fs.existsSync(verFile)) {
    try {
      const parsed = JSON.parse(fs.readFileSync(verFile, 'utf8'));
      const major = Number(parsed.MajorVersion);
      const minor = Number(parsed.MinorVersion);
      const patch = Number(parsed.PatchVersion);
      if (Number.isFinite(major) && Number.isFinite(minor)) {
        return {
          association: `${major}.${minor}`,
          fullVersion: Number.isFinite(patch) ? `${major}.${minor}.${patch}` : `${major}.${minor}`,
        };
      }
    } catch {}
  }
  const m = String(fallbackVersion || path.basename(ueRoot)).match(/(\d+\.\d+)/);
  const assoc = m ? m[1] : '5.5';
  return { association: assoc, fullVersion: fallbackVersion || assoc };
}

function generateUeProjectGuid() {
  return crypto.randomBytes(16).toString('hex').toUpperCase();
}

function walkRelativeFiles(rootDir, currentDir = rootDir, out = []) {
  for (const entry of fs.readdirSync(currentDir, { withFileTypes: true })) {
    const abs = path.join(currentDir, entry.name);
    if (entry.isDirectory()) {
      if (SKIP_DIR_NAMES.has(entry.name.toLowerCase())) continue;
      walkRelativeFiles(rootDir, abs, out);
    } else if (entry.isFile()) {
      if (SKIP_FILE_NAMES.has(entry.name.toLowerCase())) continue;
      out.push(path.relative(rootDir, abs));
    }
  }
  return out;
}

class UEProjectService {
  constructor(configStore, stateHub) {
    this.configStore = configStore;
    this.stateHub = stateHub;
  }

  async listInstalledEngines() {
    const cfg = this.configStore.get();
    const installs = await detectUE5Installations(cfg.UE5Root || '');
    return installs.map((item) => {
      const v = readEngineVersionInfo(item.path, item.version);
      const hasCppTemplate = fs.existsSync(path.join(item.path, 'Templates', 'TP_Blank', 'TP_Blank.uproject'));
      const hasBpTemplate = fs.existsSync(path.join(item.path, 'Templates', 'TP_BlankBP', 'TP_BlankBP.uproject'));
      return {
        path: item.path,
        version: v.association,
        fullVersion: v.fullVersion,
        label: `UE ${v.association} (${v.fullVersion}) — ${item.path}`,
        hasCppTemplate,
        hasBpTemplate,
      };
    });
  }

  _guardTargetDir(targetDir, projectName) {
    const cfg = this.configStore.get();
    const resolved = path.resolve(targetDir);

    // Block P4D server depot root (P4ROOT)
    const normTarget = resolved.toLowerCase();
    const normDepot = cfg.P4DepotRoot ? path.resolve(cfg.P4DepotRoot).toLowerCase() : '';
    const looksLikeP4Root =
      (normDepot && (normTarget === normDepot || normTarget.startsWith(normDepot + path.sep))) ||
      fs.existsSync(path.join(resolved, 'db.have')) ||
      fs.existsSync(path.join(resolved, 'db.rev')) ||
      fs.existsSync(path.join(resolved, 'db.domain'));
    if (looksLikeP4Root) {
      throw new Error(
        `대상 폴더(${resolved})는 Perforce 서버 원본 디포(P4ROOT) 경로입니다! C:\\BuildSystem\\Workspace\\${projectName} 같은 독립 폴더를 지정해 주세요.`
      );
    }

    // Refuse overwriting an existing project
    if (fs.existsSync(resolved)) {
      const entries = fs.readdirSync(resolved);
      const existingUproj = entries.find((f) => f.toLowerCase().endsWith('.uproject'));
      if (existingUproj) {
        throw new Error(`대상 폴더(${resolved})에 이미 프로젝트 파일(${existingUproj})이 존재합니다. 비어 있는 새 폴더를 지정해 주세요.`);
      }
      if (entries.some((f) => ['source', 'config'].includes(f.toLowerCase()))) {
        throw new Error(`대상 폴더(${resolved})에 이미 Source 또는 Config 폴더가 있습니다. 비어 있는 새 폴더를 지정해 주세요.`);
      }
    }

    return resolved;
  }

  _writeFallbackBlankProject({ targetDir, projectName, projectType, engineAssociation }) {
    const uproject = {
      FileVersion: 3,
      EngineAssociation: engineAssociation,
      Category: '',
      Description: '',
      Modules:
        projectType === 'cpp'
          ? [{ Name: projectName, Type: 'Runtime', LoadingPhase: 'Default' }]
          : [],
      Plugins: [
        {
          Name: 'ModelingToolsEditorMode',
          Enabled: true,
          TargetAllowList: ['Editor'],
        },
      ],
    };

    const files = [];
    const writeRel = (relPath, content) => {
      const abs = path.join(targetDir, relPath);
      fs.mkdirSync(path.dirname(abs), { recursive: true });
      fs.writeFileSync(abs, content, 'utf8');
      files.push(relPath);
    };

    writeRel(`${projectName}.uproject`, JSON.stringify(uproject, null, '\t') + '\n');
    writeRel('Config\\DefaultEditor.ini', '\r\n');
    writeRel(
      'Config\\DefaultEngine.ini',
      [
        '[/Script/EngineSettings.GameMapsSettings]',
        'GameDefaultMap=/Engine/Maps/Templates/OpenWorld',
        '',
        '[/Script/Engine.RendererSettings]',
        'r.AllowStaticLighting=False',
        'r.Shadow.Virtual.Enable=1',
        '',
        '[/Script/WindowsTargetPlatform.WindowsTargetSettings]',
        'DefaultGraphicsRHI=DefaultGraphicsRHI_DX12',
        '',
      ].join('\r\n')
    );
    writeRel(
      'Config\\DefaultGame.ini',
      ['[/Script/EngineSettings.GeneralProjectSettings]', `ProjectID=${generateUeProjectGuid()}`, ''].join('\r\n')
    );
    writeRel('Config\\DefaultInput.ini', '[/Script/Engine.InputSettings]\r\nDefaultPlayerInputClass=/Script/EnhancedInput.EnhancedPlayerInput\r\nDefaultInputComponentClass=/Script/EnhancedInput.EnhancedInputComponent\r\n');

    if (projectType === 'cpp') {
      const includeOrderVer = `Unreal${engineAssociation.replace('.', '_')}`;
      writeRel(
        `Source\\${projectName}.Target.cs`,
        [
          '// Copyright Epic Games, Inc. All Rights Reserved.',
          '',
          'using UnrealBuildTool;',
          'using System.Collections.Generic;',
          '',
          `public class ${projectName}Target : TargetRules`,
          '{',
          `\tpublic ${projectName}Target(TargetInfo Target) : base(Target)`,
          '\t{',
          '\t\tType = TargetType.Game;',
          '\t\tDefaultBuildSettings = BuildSettingsVersion.Latest;',
          `\t\tIncludeOrderVersion = EngineIncludeOrderVersion.${includeOrderVer};`,
          `\t\tExtraModuleNames.Add("${projectName}");`,
          '\t}',
          '}',
          '',
        ].join('\r\n')
      );
      writeRel(
        `Source\\${projectName}Editor.Target.cs`,
        [
          '// Copyright Epic Games, Inc. All Rights Reserved.',
          '',
          'using UnrealBuildTool;',
          'using System.Collections.Generic;',
          '',
          `public class ${projectName}EditorTarget : TargetRules`,
          '{',
          `\tpublic ${projectName}EditorTarget(TargetInfo Target) : base(Target)`,
          '\t{',
          '\t\tType = TargetType.Editor;',
          '\t\tDefaultBuildSettings = BuildSettingsVersion.Latest;',
          `\t\tIncludeOrderVersion = EngineIncludeOrderVersion.${includeOrderVer};`,
          `\t\tExtraModuleNames.Add("${projectName}");`,
          '\t}',
          '}',
          '',
        ].join('\r\n')
      );
      writeRel(
        `Source\\${projectName}\\${projectName}.Build.cs`,
        [
          '// Copyright Epic Games, Inc. All Rights Reserved.',
          '',
          'using UnrealBuildTool;',
          '',
          `public class ${projectName} : ModuleRules`,
          '{',
          `\tpublic ${projectName}(ReadOnlyTargetRules Target) : base(Target)`,
          '\t{',
          '\t\tPCHUsage = PCHUsageMode.UseExplicitOrSharedPCHs;',
          '',
          '\t\tPublicDependencyModuleNames.AddRange(new string[] { "Core", "CoreUObject", "Engine", "InputCore", "EnhancedInput" });',
          '\t\tPrivateDependencyModuleNames.AddRange(new string[] { });',
          '\t}',
          '}',
          '',
        ].join('\r\n')
      );
      writeRel(
        `Source\\${projectName}\\${projectName}.h`,
        ['// Copyright Epic Games, Inc. All Rights Reserved.', '', '#pragma once', '', '#include "CoreMinimal.h"', ''].join('\r\n')
      );
      writeRel(
        `Source\\${projectName}\\${projectName}.cpp`,
        [
          '// Copyright Epic Games, Inc. All Rights Reserved.',
          '',
          `#include "${projectName}.h"`,
          '#include "Modules/ModuleManager.h"',
          '',
          `IMPLEMENT_PRIMARY_GAME_MODULE( FDefaultGameModuleImpl, ${projectName}, "${projectName}" );`,
          '',
        ].join('\r\n')
      );
    }

    return files;
  }

  async createBlankProject({
    ue5Root,
    projectName,
    projectType = 'cpp',
    targetDir = '',
    includeP4Ignore = true,
    includeGitIgnore = true,
    submitToPerforce = false,
    adminUser = '',
    p4Stream = '',
    updateProjectDirConfig = true,
  }) {
    const cleanName = validateProjectName(projectName);
    const kind = projectType === 'bp' ? 'bp' : 'cpp';

    // Strictly enforce installed UE5 version selection
    const installed = await this.listInstalledEngines();
    if (installed.length === 0) {
      throw new Error('이 PC에 설치된 Unreal Engine 5를 찾을 수 없습니다. 먼저 Epic Games Launcher에서 UE5를 설치해 주세요.');
    }
    const normReq = ue5Root ? path.resolve(ue5Root).toLowerCase() : '';
    const matchedEngine = installed.find((e) => e.path.toLowerCase() === normReq);
    if (!matchedEngine) {
      throw new Error('선택한 Unreal Engine 경로가 이 PC에 설치된 공식 UE5 목록과 일치하지 않습니다. 드롭다운에서 설치된 버전을 선택해 주세요.');
    }

    const cfg = this.configStore.get();
    const resolvedDir = this._guardTargetDir(
      targetDir || path.join(cfg.WorkspaceRoot || 'C:\\BuildSystem\\Workspace', cleanName),
      cleanName
    );
    fs.mkdirSync(resolvedDir, { recursive: true });
    fs.mkdirSync(path.join(resolvedDir, 'Content'), { recursive: true });

    const templateName = kind === 'cpp' ? 'TP_Blank' : 'TP_BlankBP';
    const templateDir = path.join(matchedEngine.path, 'Templates', templateName);
    const hasOfficialTemplate = fs.existsSync(path.join(templateDir, `${templateName}.uproject`));

    let createdRelFiles = [];
    this.stateHub.appendLog(
      `=== [UE5 빈 프로젝트 생성] ${cleanName} (${kind === 'cpp' ? 'C++' : 'Blueprint'} · UE ${matchedEngine.version}) -> ${resolvedDir} ===`,
      'cyan'
    );

    if (hasOfficialTemplate) {
      const tplFiles = walkRelativeFiles(templateDir);
      const tokenRegex = new RegExp(templateName, 'g');
      for (const rel of tplFiles) {
        const mappedRel = rel.replace(tokenRegex, cleanName);
        const srcAbs = path.join(templateDir, rel);
        const dstAbs = path.join(resolvedDir, mappedRel);
        fs.mkdirSync(path.dirname(dstAbs), { recursive: true });

        const ext = path.extname(mappedRel).toLowerCase();
        if (TEXT_EXTENSIONS.has(ext)) {
          let content = fs.readFileSync(srcAbs, 'utf8').replace(tokenRegex, cleanName);
          if (ext === '.uproject') {
            try {
              const obj = JSON.parse(content);
              obj.EngineAssociation = matchedEngine.version;
              content = JSON.stringify(obj, null, '\t') + '\n';
            } catch {
              content = content.replace(/"EngineAssociation"\s*:\s*"[^"]*"/, `"EngineAssociation": "${matchedEngine.version}"`);
            }
          }
          fs.writeFileSync(dstAbs, content, 'utf8');
        } else {
          fs.copyFileSync(srcAbs, dstAbs);
        }
        createdRelFiles.push(mappedRel);
      }

      // Ensure unique ProjectID in DefaultGame.ini (just like UE5 Project Browser)
      const defaultGamePath = path.join(resolvedDir, 'Config', 'DefaultGame.ini');
      let gameIni = fs.existsSync(defaultGamePath) ? fs.readFileSync(defaultGamePath, 'utf8') : '';
      if (!/ProjectID=/i.test(gameIni)) {
        const block = `\r\n[/Script/EngineSettings.GeneralProjectSettings]\r\nProjectID=${generateUeProjectGuid()}\r\n`;
        fs.mkdirSync(path.dirname(defaultGamePath), { recursive: true });
        fs.writeFileSync(defaultGamePath, gameIni.trimEnd() + block, 'utf8');
        if (!createdRelFiles.some((f) => f.toLowerCase() === 'config\\defaultgame.ini')) {
          createdRelFiles.push('Config\\DefaultGame.ini');
        }
      }
    } else {
      createdRelFiles = this._writeFallbackBlankProject({
        targetDir: resolvedDir,
        projectName: cleanName,
        projectType: kind,
        engineAssociation: matchedEngine.version,
      });
    }

    if (includeP4Ignore) {
      fs.writeFileSync(path.join(resolvedDir, '.p4ignore'), UE5_P4IGNORE_CONTENT, 'utf8');
      if (!createdRelFiles.includes('.p4ignore')) createdRelFiles.push('.p4ignore');
    }
    if (includeGitIgnore) {
      fs.writeFileSync(path.join(resolvedDir, '.gitignore'), UE5_GITIGNORE_CONTENT, 'utf8');
      if (!createdRelFiles.includes('.gitignore')) createdRelFiles.push('.gitignore');
    }

    this.stateHub.appendLog(
      `✔ [UE5 빈 프로젝트 생성 완료] ${cleanName}.uproject (총 ${createdRelFiles.length}개 파일, ${hasOfficialTemplate ? `공식 ${templateName} 템플릿` : '표준 내장 템플릿'})`,
      'success'
    );

    // Optionally save UE5Root & ProjectDir
    if (updateProjectDirConfig) {
      this.configStore.save({
        UE5Root: matchedEngine.path,
        ProjectDir: resolvedDir,
      });
    }

    let p4SubmitResult = null;
    if (submitToPerforce) {
      p4SubmitResult = await this.submitInitialProjectToPerforce({
        projectDir: resolvedDir,
        projectName: cleanName,
        projectType: kind,
        engineVersion: matchedEngine.version,
        relFiles: createdRelFiles,
        adminUser,
        p4Stream: p4Stream || cfg.P4Stream,
      });
    }

    return {
      ok: true,
      projectName: cleanName,
      projectType: kind,
      engineVersion: matchedEngine.version,
      fullVersion: matchedEngine.fullVersion,
      targetDir: resolvedDir,
      uprojectPath: path.join(resolvedDir, `${cleanName}.uproject`),
      filesCreated: createdRelFiles,
      templateSource: hasOfficialTemplate ? templateName : 'fallback',
      p4Submit: p4SubmitResult,
    };
  }

  async submitInitialProjectToPerforce({
    projectDir,
    projectName,
    projectType,
    engineVersion,
    relFiles,
    adminUser,
    p4Stream,
  }) {
    const cfg = this.configStore.get();
    const port = cfg.P4Port || 'localhost:1666';
    const stream = String(p4Stream || cfg.P4Stream || '').trim().replace(/\/+$/, '');
    const admin = String(adminUser || '').trim();

    if (!admin) {
      throw new Error('Perforce 최초 Submit을 위해 관리자 P4 아이디(super 권한)를 입력해 주세요.');
    }
    if (!stream || !stream.startsWith('//')) {
      throw new Error(`유효한 Perforce Stream 경로가 필요합니다 (예: //MyProject/main). 현재: ${stream || '(비어 있음)'}`);
    }

    const base = ['-p', port, '-u', admin];

    // Verify admin login ticket
    const loginChk = await execCapture('p4', [...base, 'login', '-s'], { timeoutMs: 6000 });
    if (loginChk.code !== 0) {
      throw new Error(`관리자 '${admin}' Perforce 로그인 티켓이 없습니다. 먼저 [Perforce & 미러링] 탭에서 관리자 로그인을 완료해 주세요.`);
    }

    // Safety guard: refuse if depot stream already has a .uproject file
    const existingUproj = await execCapture('p4', [...base, 'files', '-e', `${stream}/*.uproject`], { timeoutMs: 6000 });
    if (existingUproj.code === 0 && /\.uproject#\d+/i.test(existingUproj.stdout || '')) {
      throw new Error(
        `스트림(${stream})에 이미 .uproject 파일이 등록되어 있습니다! 기존 프로젝트 덮어쓰기를 방지하기 위해 자동 최초 Submit을 중단했습니다. (로컬 프로젝트 폴더는 생성되었습니다.)`
      );
    }

    const tmpClient = `ws-init-bootstrap-${Date.now().toString(36).slice(-4)}`;
    const host = os.hostname();
    const clientSpec = [
      `Client:\t${tmpClient}`,
      `Owner:\t${admin}`,
      `Host:\t${host}`,
      `Description:\tBuildServerKit temporary bootstrap workspace for initial CL submit`,
      `Root:\t${projectDir}`,
      `Options:\tallwrite clobber nocompress unlocked nomodtime rmdir`,
      `SubmitOptions:\tsubmitunchanged`,
      `LineEnd:\tlocal`,
      `Stream:\t${stream}`,
    ].join('\n') + '\n';

    this.stateHub.appendLog(`=== [Perforce 최초 Submit 시작] ${stream} (계정: ${admin}, 파일 ${relFiles.length}개) ===`, 'cyan');

    const createRes = await execWithStdin('p4', [...base, 'client', '-i'], clientSpec, { timeoutMs: 8000 });
    if (createRes.code !== 0) {
      throw new Error(`임시 부트스트랩 워크스페이스 생성 실패: ${(createRes.stderr || createRes.stdout).trim()}`);
    }

    let submittedCL = '';
    try {
      // Mark exact generated files for add (-f ensures dotfiles like .p4ignore/.gitignore are never skipped)
      const absFiles = relFiles.map((r) => path.join(projectDir, r)).filter((p) => fs.existsSync(p));
      const addRes = await execCapture('p4', [...base, '-c', tmpClient, 'add', '-f', ...absFiles], {
        cwd: projectDir,
        timeoutMs: 15000,
      });
      if (addRes.code !== 0) {
        throw new Error(`p4 add 실패: ${(addRes.stderr || addRes.stdout).trim()}`);
      }

      const typeLabel = projectType === 'cpp' ? 'C++' : 'Blueprint';
      const desc = `Initial UE ${engineVersion} ${typeLabel} blank project (${projectName})`;
      const subRes = await execCapture('p4', [...base, '-c', tmpClient, 'submit', '-d', desc], {
        cwd: projectDir,
        timeoutMs: 30000,
      });
      if (subRes.code !== 0) {
        throw new Error(`p4 submit 실패: ${(subRes.stderr || subRes.stdout).trim()}`);
      }

      const m = (subRes.stdout || '').match(/Change\s+(\d+)\s+submitted/i);
      submittedCL = m ? m[1] : '1';
      this.stateHub.appendLog(`✔ [Perforce 최초 Submit 완료] CL #${submittedCL} (${stream})`, 'success');
    } finally {
      // Revert any leftover open files and delete temporary workspace so 0/20 quota is consumed
      await execCapture('p4', [...base, '-c', tmpClient, 'revert', '//...'], { timeoutMs: 6000 }).catch(() => {});
      await execCapture('p4', [...base, 'client', '-f', '-d', tmpClient], { timeoutMs: 6000 }).catch(() => {});
    }

    // Keep ws-build-full aligned with newly submitted projectDir and sync it cleanly
    const buildClient = cfg.P4BuildClient || 'ws-build-full';
    const botUser = cfg.P4User || admin;
    try {
      const cOut = await execCapture('p4', [...base, 'client', '-o', buildClient], { timeoutMs: 6000 });
      if (cOut.code === 0 && cOut.stdout) {
        const updatedSpec = cOut.stdout.replace(/^Root:.*$/m, `Root:\t${projectDir}`);
        await execWithStdin('p4', [...base, 'client', '-i'], updatedSpec, { timeoutMs: 8000 });
      }
      await execCapture('p4', ['-p', port, '-u', botUser, '-c', buildClient, 'sync', '-f', '//...#head'], { timeoutMs: 15000 });
      this.stateHub.appendLog(`✔ [빌드 워크스페이스 동기화 완료] ${buildClient} -> ${projectDir} (CL #${submittedCL})`, 'success');
    } catch {}

    return {
      ok: true,
      cl: submittedCL,
      stream,
      message: `Perforce(${stream})에 CL #${submittedCL} 최초 Submit 및 빌드 워크스페이스 동기화 완료!`,
    };
  }
}

module.exports = { UEProjectService, validateProjectName };
